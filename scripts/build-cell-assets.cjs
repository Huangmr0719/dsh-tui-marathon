// Build-time geometry only; the default renderer never decodes image frames.
const fs = require('node:fs')
const path = require('node:path')
const { gzipSync } = require('node:zlib')
const { loadImage, createCanvas } = require(process.argv[2] || '@napi-rs/canvas')
const root = path.resolve(__dirname, '..')
const assets = path.join(root, 'assets')

async function main() {
  const svg = fs.readFileSync(path.join(assets, 'deepseek.svg'), 'utf8')
  const commands = svg.match(/\sd="([^"]+)"/)[1].match(/[MCZ]|-?\d+(?:\.\d+)?/g)
  const contours = []
  let i = 0, points, x = 0, y = 0
  const number = () => Number(commands[i++])
  while (i < commands.length) {
    const command = commands[i++]
    if (command === 'M') { x = number(); y = number(); points = [x, y]; contours.push(points) }
    else if (command === 'C') {
      const x1 = number(), y1 = number(), x2 = number(), y2 = number(), x3 = number(), y3 = number()
      for (let step = 1; step <= 12; step++) {
        const t = step / 12, u = 1 - t
        points.push(...[u*u*u*x + 3*u*u*t*x1 + 3*u*t*t*x2 + t*t*t*x3,
          u*u*u*y + 3*u*u*t*y1 + 3*u*t*t*y2 + t*t*t*y3].map(v => Math.round(v * 1000) / 1000))
      }
      x = x3; y = y3
    } else if (command !== 'Z') throw new Error(`Unsupported logo command: ${command}`)
  }
  const image = await loadImage(path.join(assets, 'blue-pixel.png'))
  const canvas = createCanvas(64, 64), g = canvas.getContext('2d')
  g.imageSmoothingEnabled = false
  g.drawImage(image, 0, 0, 64, 64)
  const pixels = g.getImageData(0, 0, 64, 64).data
  const sprite = Array.from({ length: 64 }, (_, y) => Array.from({ length: 64 }, (_, x) => pixels[(y * 64 + x) * 4 + 2] > 128 ? '1' : '0').join(''))
  fs.writeFileSync(path.join(root, 'src/artwork.ts'),
    '// Generated by scripts/build-cell-assets.cjs. DeepSeek logo contours and MLS pixel sprite.\n' +
    `export const whaleContours: readonly (readonly number[])[] = ${JSON.stringify(contours)}\n` +
    `export const pixelWhale: readonly string[] = ${JSON.stringify(sprite, null, 2)}\n`)
  const logo = createCanvas(256, 256), context = logo.getContext('2d')
  const colored = svg.replace(/fill="[^"]*"/g, 'fill="#D7FF00"')
  context.drawImage(await loadImage(Buffer.from(colored)), 0, 0, 256, 256)
  fs.writeFileSync(path.join(assets, 'logo.rgba.gz'), gzipSync(context.getImageData(0, 0, 256, 256).data))
  console.log(`Generated ${contours.length} contours, a 64×64 sprite and one optional 256×256 logo`)
}
main().catch(error => { console.error(error); process.exitCode = 1 })
